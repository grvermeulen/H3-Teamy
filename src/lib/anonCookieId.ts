/** Whether a guest cookie is an opaque UUID rather than a public account identifier. */
export function isAnonCookieId(
  value: string | undefined | null,
): value is string {
  return (
    typeof value === "string" &&
    /^[0-9a-f]{8}-[0-9a-f]{4}-[1-8][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i.test(
      value,
    )
  );
}
